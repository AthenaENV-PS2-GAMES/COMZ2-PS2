import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PlayerSight,sampleCurve} from '../player_weapon_visuals.js';
const m=JSON.parse(readFileSync(new URL('../AthenaModels/WeaponFX/visuals.json',import.meta.url)));
const s=new PlayerSight(m.reticle),out={};
assert.equal(s.stretch,1);s.sample(448,out,()=>0.5);assert.ok(out.x===0&&out.y===0);
s.kick();assert.equal(s.stretch,11);
s.sample(448,out,()=>0.5);assert.ok(Math.abs(Math.hypot(out.x,out.y)-10*1.4*Math.SQRT1_2)<1e-8);
s.update(0.1,false);assert.equal(s.stretch,8);
s.kick();s.kick();assert.equal(s.stretch,20,'MP5 expansion is capped at original maximum');
for(let i=0;i<100;i++)s.update(1/60,false);
assert.equal(s.stretch,1);s.update(1,true);assert.equal(s.stretch,5);
s.sample(448,out,()=>0.5);assert.equal(Math.hypot(out.x,out.y),0,'spread is measured from the running rest position');
s.locked=true;s.reset();assert.equal(s.locked,false);assert.equal(s.stretch,1);
const root=m.effects.muzzle.layers[0];assert.equal(sampleCurve(root.sizeCurve.maxCurve,0),0);
assert.equal(sampleCurve(root.sizeCurve.maxCurve,1),1);
assert.equal(m.effects.muzzle.layers[1].uv.rows,3);
assert.equal(m.effects.muzzle.layers[1].uv.randomRow,true);
assert.equal(m.reticle.color[0],0);assert.ok(m.reticle.color[1]>0.8);
console.log('Weapon visuals: original reticle, pre-recoil disk sampling, recovery, running rest, cap, cubic curves and flipbook rows passed');
